var FALLBACK_NOTE = "（以上内容为 AI 基于牌面意象的开放式解读，仅供娱乐与自我探索，不构成任何预测、诊断或建议。）";

function applyTable(text, table) {
  for (var i = 0; i < table.length; i++) {
    // 用 split/join 做全局替换，避免正则转义问题
    var parts = text.split(table[i][0]);
    if (parts.length > 1) {
      text = parts.join(table[i][1]);
    }
  }
  return text;
}

// 过滤入口：返回 { text, dirty }，dirty 表示命中过红线（用于日志/审计）。
function filter(text) {
  if (!text || typeof text !== "string") return { text: "", dirty: false };
  var dirty = false;

  // 先硬词
  for (var i = 0; i < HARD.length; i++) {
    if (text.indexOf(HARD[i][0]) !== -1) dirty = true;
  }
  text = applyTable(text, HARD);

  // 再软短语
  text = applyTable(text, SOFT);

  // 残留兜底：对仍存活的红线词做最后一次中性替换，确保绝不输出红线词
  var residualHit = false;
  for (var k = 0; k < RESIDUAL_REPLACE.length; k++) {
    if (text.indexOf(RESIDUAL_REPLACE[k][0]) !== -1) {
      residualHit = true;
      text = applyTable(text, [RESIDUAL_REPLACE[k]]);
    }
  }
  if (residualHit) {
    dirty = true;
    if (text.indexOf(FALLBACK_NOTE) === -1) text = text + FALLBACK_NOTE;
  }

  return { text: text, dirty: dirty };
}

module.exports = { filter: filter, FALLBACK_NOTE: FALLBACK_NOTE };
